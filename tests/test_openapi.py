from pathlib import Path

from docscout.analyze.apitypes.openapi import Resolver, has_example, is_generated, parse_spec, score_spec

SPECS = Path(__file__).parent / "fixtures" / "specs"


def load(name):
    return (SPECS / name).read_bytes()


def test_bare_spec_scores_high_with_reasons():
    report = score_spec(load("bare.yaml"), "api/openapi.yaml")
    assert report.version == "OpenAPI 3.0.3" and report.operations == 4
    assert report.gap == 75  # 20 + 7.5 + 15 + 7.5 + 10 + overview 10 + servers 5; no security schemes or tags to check
    texts = [f.text for f in report.findings]
    assert "4/4 operations have no summary or description" in texts
    assert "2/4 operations have parameters without descriptions" in texts
    assert "4/4 operations have no request or response examples" in texts
    assert "4/4 operations document no error responses" in texts
    # DELETE returns 204, so only the 3 others lack a success schema.
    assert "3/4 operations have no schema for a successful response" in texts
    first = report.findings[0]
    assert first.examples == ["GET /checks", "POST /checks"] and first.more == 2
    assert report.failing_operations == 4
    assert not report.generated


def test_well_documented_spec_scores_low():
    report = score_spec(load("good.yaml"))
    assert report.gap <= 10, report.points
    assert report.failing_operations <= 1


def test_swagger2_is_scored_with_its_own_rules():
    report = score_spec(load("swagger2.json"))
    assert report.version == "Swagger 2.0" and report.operations == 3
    texts = [f.text for f in report.findings]
    assert "1/3 operations have no summary or description" in texts  # POST /pets
    assert "1/1 authentication schemes have no description" in texts
    assert not any("server address" in t for t in texts)  # host is set


def test_small_or_invalid_files_are_not_scored():
    assert score_spec("openapi: 3.0.0\npaths:\n  /a:\n    get: {}\n") is None  # fewer than 3 operations
    assert score_spec("just: yaml") is None
    assert score_spec("a: &x [1]\nb: *x\n") is None  # aliases rejected
    assert parse_spec(b"{not json") is None


def test_generated_specs_are_flagged():
    header = b"# Code generated by swag. DO NOT EDIT\n" + load("bare.yaml")
    assert score_spec(header).generated
    assert is_generated(load("bare.yaml"), "docs/generated/openapi.yaml")
    assert not is_generated(load("bare.yaml"), "api/openapi.yaml")


def test_resolver_stops_at_cycles_and_external_refs():
    doc = {"a": {"$ref": "#/b"}, "b": {"$ref": "#/a"}, "ext": {"$ref": "other.yaml#/x"}, "c": {"$ref": "#/d~1e"}, "d/e": {"ok": 1}}
    r = Resolver(doc)
    assert r.resolve(doc["a"]) == {}
    assert r.resolve(doc["ext"]) == {}
    assert r.resolve(doc["c"]) == {"ok": 1}
    encoded = {"paths": {"/sec/{id}": {"get": {}}, "/alias/{id}": {"$ref": "#/paths/~1sec~1%7Bid%7D"}}}  # sharry, 17 Oct
    assert Resolver(encoded).resolve(encoded["paths"]["/alias/{id}"]) == {"get": {}}
    self_ref = {"definitions": {"Pet": {"properties": {"self": {"$ref": "#/definitions/Pet"}}}}}
    assert not has_example(self_ref["definitions"]["Pet"], Resolver(self_ref))  # terminates
